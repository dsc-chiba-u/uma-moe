"""Build the model-independent text corpora of the locality study (raw downloads are cached).

    .venv/bin/python -I locality/corpora.py        -> results/locality/corpora/{docs/*.txt, raw/*, corpora.json}

Every document is plain text; the per-model token budgets (6,144 tokens for a domain document, 4,096 per block of
the mixed long document, 32,768 for a long document) are applied after tokenization (locality/run_model.py).

Domains (two documents each) and long documents:
  code      code_py   llama.cpp conversion/base.py           code_cpp  llama.cpp src/llama-graph.cpp
  prose     en_wiki   Wikipedia: Photosynthesis, Roman Empire  en_fiction  Doyle, The Adventures of Sherlock Holmes
  ja        ja_wiki   Wikipedia ja: 光合成, 江戸時代            ja_lit      夏目漱石『こころ』 (Aozora Bunko)
  math      math_gsm8k  GSM8K test problems + solutions      math_comp   MATH-500 problems + LaTeX solutions
  long      long_mixed  8 blocks of different domains (topic shift every 4,096 tokens), sources disjoint from above
            long_book   Austen, Pride and Prejudice           long_code   Strata setup.py + DETAILS.md + generate.cpp
            (bench/data/longdoc.txt, the long prompts of the main study)
The chat and dialog corpora are generated by each model (locality/run_model.py, stage gen).
"""
import html
import json
import re
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "results/locality/corpora"
RAW, DOCS = OUT / "raw", OUT / "docs"
LLAMA = Path.home() / "src/llama.cpp-master"
UA = {"User-Agent": "uma-moe-locality-study/0.1 (research script)"}


def fetch(name, url):
    p = RAW / name
    if not p.exists():
        req = urllib.request.Request(url, headers=UA)
        with urllib.request.urlopen(req, timeout=60) as r:
            p.write_bytes(r.read())
        time.sleep(1.0)
    return p.read_bytes()


def wiki(lang, title, n_chars):
    url = (f"https://{lang}.wikipedia.org/w/api.php?action=query&prop=extracts&explaintext=1&redirects=1&format=json&titles="
           + urllib.parse.quote(title))
    d = json.loads(fetch(f"wiki_{lang}_{title}.json", url))
    page = next(iter(d["query"]["pages"].values()))
    text = page["extract"]
    text = re.sub(r"\n{3,}", "\n\n", text)
    return f"{page['title']}\n\n{text[:n_chars]}"


def gutenberg(num, start_marker, n_chars):
    t = fetch(f"pg{num}.txt", f"https://www.gutenberg.org/cache/epub/{num}/pg{num}.txt").decode("utf-8-sig")
    t = t.replace("\r\n", "\n")
    i = t.find(start_marker)
    if i < 0:
        raise ValueError(f"pg{num}: marker {start_marker!r} not found")
    return t[i:i + n_chars]


def aozora(path, n_chars):
    raw = fetch(path.replace("/", "_"), f"https://www.aozora.gr.jp/cards/{path}").decode("cp932", errors="replace")
    body = raw[raw.find('<div class="main_text">'):]
    body = body[:body.find('<div class="bibliographical_information">')]
    body = re.sub(r"<rt>.*?</rt>|<rp>.*?</rp>", "", body, flags=re.S)
    body = re.sub(r"<br\s*/?>", "\n", body)
    body = re.sub(r"<[^>]+>", "", body)
    body = html.unescape(body)
    body = re.sub(r"[ \t　]*\n", "\n", body)
    body = re.sub(r"\n{3,}", "\n\n", body).strip()
    return body[:n_chars]


def gsm8k(offset, n):
    rows = []
    for o in range(offset, offset + n, 100):
        url = (f"https://datasets-server.huggingface.co/rows?dataset=openai/gsm8k&config=main&split=test"
               f"&offset={o}&length={min(100, offset + n - o)}")
        rows += [r["row"] for r in json.loads(fetch(f"gsm8k_test_{o}.json", url))["rows"]]
    out = []
    for r in rows:
        ans = re.sub(r"<<[^>]*>>", "", r["answer"]).replace("#### ", "Final answer: ")
        out.append(f"Question: {r['question']}\nAnswer: {ans}")
    return "\n\n".join(out)


def math500(lo, hi):
    from huggingface_hub import hf_hub_download
    p = hf_hub_download("HuggingFaceH4/MATH-500", "test.jsonl", repo_type="dataset", local_dir=RAW / "math500")
    rows = [json.loads(line) for line in open(p)][lo:hi]
    return "\n\n".join(f"Problem ({r['subject']}, level {r['level']}): {r['problem']}\n\nSolution: {r['solution']}" for r in rows)


def source(path, start, n_chars):
    t = Path(path).read_text()
    return t[start:start + n_chars]


def main():
    RAW.mkdir(parents=True, exist_ok=True)
    DOCS.mkdir(parents=True, exist_ok=True)
    docs = {
        "code_py": source(LLAMA / "conversion/base.py", 0, 60000),
        "code_cpp": source(LLAMA / "src/llama-graph.cpp", 0, 60000),
        "en_wiki": wiki("en", "Photosynthesis", 20000) + "\n\n" + wiki("en", "Roman Empire", 20000),
        "en_fiction": gutenberg(1661, "A SCANDAL IN BOHEMIA\n\n\nI.", 45000),
        "ja_wiki": wiki("ja", "光合成", 12000) + "\n\n" + wiki("ja", "江戸時代", 12000),
        "ja_lit": aozora("000148/files/773_14560.html", 25000),
        "math_gsm8k": gsm8k(0, 100),
        "math_comp": math500(0, 60),
        "long_book": gutenberg(1342, "Chapter I.]", 200000),
        "long_code": (ROOT / "bench/data/longdoc.txt").read_text()[:200000],
    }
    if len(docs["long_book"]) < 150000:
        raise ValueError("long_book too short")
    blocks = [   # long_mixed: one topic shift every 4,096 tokens
        ("en_wiki", wiki("en", "Plate tectonics", 40000)),
        ("code_py", source(LLAMA / "gguf-py/gguf/gguf_writer.py", 0, 40000)),
        ("ja_wiki", wiki("ja", "富士山", 20000)),
        ("math", math500(250, 300)),
        ("en_fiction", gutenberg(98, "CHAPTER I.\nThe Period", 40000)),
        ("code_cpp", source(LLAMA / "ggml/src/ggml-cuda/ggml-cuda.cu", 0, 40000)),
        ("ja_lit", aozora("000081/files/456_15050.html", 20000)),
        ("en_wiki", wiki("en", "Jazz", 40000)),
    ]
    meta = {"docs": {}, "long_mixed_blocks": []}
    for name, text in docs.items():
        (DOCS / f"{name}.txt").write_text(text)
        meta["docs"][name] = {"chars": len(text)}
    for i, (dom, text) in enumerate(blocks):
        (DOCS / f"long_mixed_{i}.txt").write_text(text)
        meta["long_mixed_blocks"].append({"block": i, "domain": dom, "chars": len(text)})
    json.dump(meta, open(OUT / "corpora.json", "w"), indent=1, ensure_ascii=False)
    for name, d in meta["docs"].items():
        print(f"{name:12s} {d['chars']:7d} chars")
    for b in meta["long_mixed_blocks"]:
        print(f"long_mixed_{b['block']} {b['domain']:10s} {b['chars']:7d} chars")


if __name__ == "__main__":
    sys.exit(main())
